/**
 * 把一段文本里所有 PEM 证书拆出来（顺序原样）
 * @param {string} text
 * @returns {string[]}
 */
export function splitPemCerts(text) {
  return text.match(/-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----/g) ?? [];
}
